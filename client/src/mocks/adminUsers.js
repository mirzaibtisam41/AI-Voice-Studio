export function getUserTransactions(user) {
  const offset = Number(user.id.slice(1));

  return TRANSACTION_TEMPLATES.map((item, index) => ({
    id: `${user.id}-tx-${index}`,
    label: item.label,
    amount: item.amount < 0 ? item.amount - offset * 7 : item.amount,
    date: `2026-10-${String(item.day).padStart(2, '0')}T12:00:00`,
  }));
}
